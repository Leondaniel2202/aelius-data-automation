"""Bundle shared modules into standalone scripts without external build dependencies.

Only top-level 'from shared.<module> import ...' imports are supported.
"""
import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SHARED = ROOT / "shared"


def bundle(source: Path, output: Path) -> None:
    script = source.read_text(encoding="utf-8")
    tree = ast.parse(script, filename=str(source))
    imports = []
    modules = []
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module and node.module.startswith("shared."):
            if node not in tree.body or node.level or node.module.count(".") != 1 or any(alias.name == "*" or alias.asname for alias in node.names):
                raise ValueError("Only top-level, non-aliased 'from shared.module import name' is supported")
            imports.append(node)
            if node.module not in modules:
                modules.append(node.module)
        if isinstance(node, ast.Import) and any(alias.name == "shared" or alias.name.startswith("shared.") for alias in node.names):
            raise ValueError("Use 'from shared.module import name' for shared modules")

    lines = script.splitlines(keepends=True)
    for node in sorted(imports, key=lambda node: node.lineno, reverse=True):
        lines[node.lineno - 1:node.end_lineno] = []

    parts = []
    for module in modules:
        path = SHARED / (module.split(".")[1] + ".py")
        if not path.is_file():
            raise FileNotFoundError(path)
        content = path.read_text(encoding="utf-8")
        parsed = ast.parse(content, filename=str(path))
        if any(isinstance(node, (ast.ImportFrom, ast.Import)) and
               ((isinstance(node, ast.ImportFrom) and node.module and node.module.startswith("shared")) or
                (isinstance(node, ast.Import) and any(alias.name.startswith("shared") for alias in node.names)))
               for node in ast.walk(parsed)):
            raise ValueError(f"Nested shared imports are not supported: {path}")
        parts.append(content)

    generated = "# Generated by automation/build/bundle.py; do not edit.\n" + "\n\n".join(parts) + "\n\n" + "".join(lines)
    compile(generated, str(output), "exec")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(generated, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=ROOT / "dist")
    args = parser.parse_args()
    for source in sorted((ROOT / "scripts").glob("*.py")):
        output = args.output / source.name
        bundle(source, output)
        print(f"Built {output}")


if __name__ == "__main__":
    main()
