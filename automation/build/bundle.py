"""Build standalone SeaTable scripts by inlining the shared.common module.

Only the explicit 'from shared.common import ...' form is supported.
No runtime secrets are embedded or injected by this builder.
"""
import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def bundle(source: Path, output: Path) -> None:
    script = source.read_text(encoding="utf-8")
    tree = ast.parse(script, filename=str(source))
    lines = script.splitlines(keepends=True)
    imports = [node for node in tree.body if isinstance(node, ast.ImportFrom) and node.module == "shared.common"]
    for node in reversed(imports):
        lines[node.lineno - 1:node.end_lineno] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module and node.module.startswith("shared.") and node not in imports:
            raise ValueError("Unsupported shared import; only top-level shared.common imports are supported")
        if isinstance(node, ast.Import) and any(alias.name.startswith("shared") for alias in node.names):
            raise ValueError("Use 'from shared.common import ...' for shared code")
    common = (ROOT / "shared" / "common.py").read_text(encoding="utf-8")
    result = "# Generated by automation/build/bundle.py; do not edit.\n" + common + "\n\n" + "".join(lines)
    compile(result, str(output), "exec")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(result, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=ROOT / "dist")
    args = parser.parse_args()
    for source in sorted((ROOT / "scripts").glob("*.py")):
        destination = args.output / source.name
        bundle(source, destination)
        print(f"Built {destination}")


if __name__ == "__main__":
    main()
